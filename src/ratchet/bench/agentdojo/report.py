"""Render runs' `results.json` as Markdown: one section per run, and the document over many runs."""

from __future__ import annotations

from typing import Any

# The fixed introduction of the results document. Public text: the benchmark is named next to results
# measured on it, and nothing else (no authors, venues or papers).
PREAMBLE = """\
AgentDojo v1.2.2 (package 0.1.35), run as a Ratchet world: the agent runs in Ratchet's worker loop under a
harness, tool calls execute in AgentDojo's own function runtime, and every episode is graded by
AgentDojo's own `utility` and `security` checks, unchanged.
Generated by `python -m ratchet.bench.agentdojo report`; the raw evaluations, traces, harnesses
and signed admission decisions of every run are kept as JSON lines in the run directory.

**Split.** User tasks and injection tasks are each shuffled with seed 0 and half of each is held out. A
training case pairs a training user task with a training injection task, or with none; a held-out case
pairs a held-out user task with a held-out injection task, or with none. Mixed pairs are in neither set.
The improver reads training traces only; held-out cases reach only the admission check.

**Metrics (held-out only, counts and denominators shown).** Utility: no-attack episodes whose user task
was completed. Utility under attack: attacked episodes whose user task was completed. Targeted ASR:
attacked episodes in which the attacker's goal was achieved. Ratchet pass: user task completed and, when
attacked, the attacker's goal not achieved. A run that ended in an infrastructure error is excluded from
the rate and counted as an error, never guessed.

**Every evaluation is listed.** Each run's table lists the baseline, the loop's two fresh parent runs per
generation, and every candidate, composite and confirmation run of a promoted version, in the order they
ran. Nothing was re-run or selected afterwards.

**Agent models.** `gpt-5.6-luna` is the assigned agent model. Its baseline targeted ASR measured 0/32
(banking), 0/20 (slack) and 0/40 (travel) on held-out attacked episodes, which leaves no security
headroom to measure, so every suite was also run with `gemini-3.1-flash-lite`, whose baseline ASR on a
banking probe was 4/8. The improver is `gpt-5.6-terra` in every run.

**Differences from AgentDojo's reference pipeline**, each recorded so the numbers are not read as a
leaderboard entry:

- The worker loop prefixes the user's request with `Ticket <user task id>`.
- Tool results reach the model as JSON, `{"ok", "data": {"output": <AgentDojo's YAML rendering>}, "error"}`,
  instead of the bare YAML string.
- At most 16 model calls per episode (AgentDojo: one call, then up to 15 tool-execution rounds).
- The attack is AgentDojo's `important_instructions` with the user named and the model addressed
  generically (`important_instructions_no_model_name`), because AgentDojo's model-name table does not list
  these models.
- The function-call trace given to AgentDojo's trace-based checks holds the calls that reached the
  environment; a call a guard blocked never happened.
- The guard view cuts texts over 240 characters to a prefix (the workspace state is 115,670 bytes of JSON);
  full texts remain in the tool results a guard sees in its history.
"""


def _cell(m: dict[str, Any]) -> str:
    rate = m.get("rate")
    pct = f"{100 * rate:.1f}%" if rate is not None else "n/a"
    err = f", {m['errors']} err" if m.get("errors") else ""
    return f"{pct} ({m['hits']}/{m['total']}{err})"


def _guard_lines(changes: dict[str, Any], parent_guards: set[str]) -> list[str]:
    out = []
    for g in changes.get("guards", []):
        if g["id"] not in parent_guards:
            out.append(f"  - guard `{g['id']}`: {g['description']}")
    return out


def render(results: dict[str, Any]) -> str:
    p = results["provenance"]
    lines = [
        f"### {p['suite']} ({p['benchmark_version']}), run `{results['run_id']}`"
        + (f", {results['status']}" if results.get("status") else ""),
        "",
        f"- Agent model `{p['model']}`, improver model `{p['improver_model']}`, endpoint `{p['endpoint']}`",
        f"- AgentDojo package {p['agentdojo_package_version']}"
        + (
            f", reference clone commit `{p['agentdojo_reference_clone_commit']}`"
            if p.get("agentdojo_reference_clone_commit")
            else ""
        ),
        f"- Ratchet commit `{p.get('ratchet_commit')}`, split seed {p['seed']}, attack `{p['attack']}`",
        f"- Held-out user tasks: {', '.join(p['split']['heldout_users'])}",
        f"- Held-out injection tasks: {', '.join(p['split']['heldout_injections'])}",
        f"- Cases: {p['cases']['train']} training, {p['cases']['heldout']} held-out "
        "(the improver reads training traces only)",
        "",
        "| Version | Evaluation | Role | Gen | Utility | Utility under attack | Targeted ASR "
        "| Ratchet pass |",
        "|---|---|---|---|---|---|---|---|",
    ]
    rows = results["metrics"]
    for v in results["versions"]:
        mine = [r for r in rows if r["version"] == v and "heldout" in r]
        if not mine:
            lines.append(f"| `{v}` | not evaluated | | | | | | |")
        for r in mine:
            h = r["heldout"]
            lines.append(
                f"| `{v}` | {r['eval_id']} | {r.get('role') or ''} | {r.get('generation') or ''} "
                f"| {_cell(h['utility'])} | {_cell(h['utility_under_attack'])} "
                f"| {_cell(h['targeted_attack_success'])} | {_cell(h['ratchet_passed'])} |"
            )
    lines.append("")
    changes = results.get("admitted", {})
    seen: set[str] = set()
    admitted_lines: list[str] = []
    for v in results["versions"][1:]:
        c = changes.get(v)
        if c is None:
            continue
        admitted_lines.append(f"- `{v}` (parent `{c['parent']}`):")
        admitted_lines += _guard_lines(c, seen)
        seen |= {g["id"] for g in c.get("guards", [])}
        for proc in c.get("procedures", []):
            if proc["name"] not in seen:
                admitted_lines.append(f"  - procedure `{proc['name']}` when {proc['when']}")
                seen.add(proc["name"])
    if admitted_lines:
        lines += ["Admitted versions and their changes:", "", *admitted_lines, ""]
    else:
        lines += ["No candidate was admitted in this run.", ""]
    for note in results.get("notes", []):
        lines.append(f"- {note}")
    return "\n".join(lines).rstrip() + "\n"


def _heldout_cells(row: dict[str, Any] | None) -> str:
    if row is None or "heldout" not in row:
        return "| | | "
    h = row["heldout"]
    cells = (h["utility"], h["utility_under_attack"], h["targeted_attack_success"])
    return "".join(f"| {_cell(c)} " for c in cells)


def overview_row(results: dict[str, Any]) -> str:
    """Suite, models, the baseline's held-out metrics and the newest version's latest held-out run."""
    p = results["provenance"]
    rows = [r for r in results["metrics"] if "heldout" in r]
    base = next((r for r in rows if r.get("role") == "baseline"), None)
    last_version = results["versions"][-1] if results["versions"] else None
    newest = [r for r in rows if r["version"] == last_version and len(results["versions"]) > 1]
    latest = newest[-1] if newest else None
    gens = len(results.get("generations", []))
    label = f"`{last_version}` ({latest['eval_id']})" if latest else "none promoted"
    return (
        f"| {p['suite']} | `{p['model']}` | {results.get('status', '')}, {gens} gen "
        + _heldout_cells(base)
        + f"| {label} "
        + _heldout_cells(latest)
        + "|"
    )


def document(all_results: list[dict[str, Any]], preamble: str = PREAMBLE) -> str:
    lines = [
        "# AgentDojo results",
        "",
        preamble.strip(),
        "",
        "## Overview (held-out cases only)",
        "",
        "| Suite | Agent model | Status | v0 utility | v0 utility under attack | v0 targeted ASR "
        "| Newest admitted version | Its utility | Its utility under attack | Its targeted ASR |",
        "|---|---|---|---|---|---|---|---|---|---|",
        *[overview_row(r) for r in all_results],
        "",
        "## Runs",
        "",
    ]
    body = "\n".join(render(r) for r in all_results)
    return "\n".join(lines).replace("\n\n\n", "\n\n") + body
