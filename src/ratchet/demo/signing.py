"""The demo's own signing key: a fresh Ed25519 key per demo run, never the pinned decision key.

`ratchet demo double-refund` must run on a machine that holds no secret, so it cannot use
`Signer.for_decisions()`, which refuses any key but the pinned one. It generates a key instead, writes only
the public half as PEM beside the demo store, and records in every signed decision that a demo key signed
it. The private half lives in memory for the length of the run and is never written.
`ratchet verify --pubkey-file <PEM>` checks those decisions against that file; under the pinned key (the
default) they do not verify, by design.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

from ratchet.improve.receipt import TRUSTED_KEY_ENV, ReceiptError, Signer
from ratchet.verify.dsse import keyid_of

DEMO_DIR_ENV = "RATCHET_DEMO_DIR"
DEFAULT_DEMO_DIR = ".ratchet-demo"
KEY_KIND = "demo"
KEY_NOTE = (
    "ephemeral Ed25519 key generated by `ratchet demo` for this run; it is NOT the pinned decision key "
    "keys/ratchet-decisions.pub, and only its public half was kept"
)


def demo_dir() -> Path:
    return Path(os.environ.get(DEMO_DIR_ENV) or DEFAULT_DEMO_DIR).resolve()


def pubkey_path(db: str, directory: Path | None = None) -> Path:
    return (directory or demo_dir()) / f"{db}-decision-key.pub"


def demo_signer(pubkey_file: Path) -> Signer:
    """A fresh signer whose public key is written to `pubkey_file` (PEM, SubjectPublicKeyInfo).

    Refuses when the fresh key equals the pinned decision key, so a demo decision can never pass for one
    the pinned key signed.
    """
    from ratchet.verify import keys  # deferred, as in receipt.Signer.for_decisions

    signer = Signer.generate()
    pinned: set[str] = set()
    for path in {keys.DEFAULT_KEY_PATH, Path(os.environ.get(TRUSTED_KEY_ENV) or keys.DEFAULT_KEY_PATH)}:
        try:
            pinned.add(keyid_of(keys.load_trusted_key(path)))
        except keys.TrustedKeyError:
            continue
    if signer.keyid in pinned:
        raise ReceiptError("the generated demo key equals the pinned decision key; refusing to sign with it")
    pubkey_file.parent.mkdir(parents=True, exist_ok=True)
    pem = signer.public_key.public_bytes(Encoding.PEM, PublicFormat.SubjectPublicKeyInfo)
    pubkey_file.write_bytes(pem)
    return signer


def signing_label(signer: Signer, pubkey_file: Path | None = None) -> dict[str, Any]:
    """What every demo decision records, inside its signed payload, about the key that signed it."""
    label: dict[str, Any] = {"kind": KEY_KIND, "keyid": signer.keyid, "note": KEY_NOTE}
    if pubkey_file is not None:
        label["pubkey_file"] = pubkey_file.name
    return label


def is_demo_signed(payload: Any) -> bool:
    """True when a signed decision payload says a demo key signed it."""
    context = payload.get("context") if isinstance(payload, dict) else None
    label = context.get("signing_key") if isinstance(context, dict) else None
    return isinstance(label, dict) and label.get("kind") == KEY_KIND
