#!/usr/bin/env python3
"""Keep the written docs true: links resolve, the results index is current, a counted claim matches the code.

    python3 scripts/check-docs.py            check; exit 1 and name every failure
    python3 scripts/check-docs.py --write    regenerate docs/RESULTS.md from docs/results/ first

Checks:
  1. every relative link in README.md and docs/**/*.md resolves to a file;
  2. docs/RESULTS.md lists every file in docs/results/ and equals what --write would produce, so a result
     added to the directory cannot be missing from the index (the index copies no number: each result file
     carries its own counts and denominators);
  3. "N case families" in the README equals the number of families in the case suite.
Run from any directory. Uses the repository's virtualenv for check 3 when it is importable.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "docs" / "results"
INDEX = ROOT / "docs" / "RESULTS.md"
LINK = re.compile(r"\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
FENCE = re.compile(r"^\s*(```|~~~)")
NUMBER_WORDS = {
    "one": 1,
    "two": 2,
    "three": 3,
    "four": 4,
    "five": 5,
    "six": 6,
    "seven": 7,
    "eight": 8,
    "nine": 9,
    "ten": 10,
    "eleven": 11,
    "twelve": 12,
}


# One line per known result file, so the index reads well. A new file falls back to its first sentence.
DESCRIPTIONS = {
    "agentdojo.md": (
        "The loop run as an AgentDojo world: held-out utility, utility under attack and attack success, "
        "graded by AgentDojo's own checks, with every evaluation listed."
    ),
    "tau-retail.md": (
        "The loop on tau-bench retail with its own database and reward: pass^k by harness and split, "
        "with crashed and stopped runs listed."
    ),
    "archive.json": (
        "The version archive export: every harness version as a node with its clade pass rate and "
        "admission yield."
    ),
}


def first_paragraph(path: Path) -> str:
    """The first prose sentence after the title of a markdown result, whitespace collapsed."""
    lines = path.read_text(encoding="utf-8").splitlines()
    para: list[str] = []
    for line in lines[1:]:
        if line.startswith("#") and not para:
            continue
        if not line.strip():
            if para:
                break
            continue
        if line.startswith(("|", "-", "*", "```")) and not para:
            continue
        para.append(line.strip())
    text = " ".join(para)
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return (match.group(1) if match else text).strip()


def title_of(path: Path) -> str:
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return path.name


def render_index() -> str:
    rows: list[str] = []
    for path in sorted(RESULTS.iterdir()):
        if not path.is_file():
            continue
        rel = path.relative_to(ROOT / "docs").as_posix()
        if path.suffix == ".md":
            about = DESCRIPTIONS.get(path.name) or first_paragraph(path)
            rows.append(f"| [{title_of(path)}]({rel}) | {about} |")
        else:
            about = DESCRIPTIONS.get(path.name) or f"Raw records (`{path.suffix.lstrip('.')}`)."
            rows.append(f"| [{path.name}]({rel}) | {about} |")
    return "\n".join(
        [
            "# Results",
            "",
            "Every measured result lives in `docs/results/` with its own counts, denominators and",
            "provenance, and this page lists each file. It copies no number. It is generated by",
            "`scripts/check-docs.py --write`, and `scripts/check-docs.py` fails when the directory and this",
            "list disagree.",
            "",
            "| Result | What it covers |",
            "|---|---|",
            *rows,
            "",
            "The rule that decides whether a change counts is in [ADMISSION.md](ADMISSION.md),",
            "and the labels FRESH, RECORDED and CACHED mean what that page says.",
            "",
        ]
    )


def links_of(path: Path) -> list[str]:
    out: list[str] = []
    fenced = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if FENCE.match(line):
            fenced = not fenced
        elif not fenced:
            out += LINK.findall(line)
    return out


def check_links() -> list[str]:
    failures: list[str] = []
    for path in [ROOT / "README.md", *sorted((ROOT / "docs").rglob("*.md"))]:
        for target in links_of(path):
            if re.match(r"^(?:[a-z][a-z0-9+.-]*:|#|//)", target, re.IGNORECASE):
                continue
            file = (path.parent / target.split("#")[0]).resolve()
            if not file.exists():
                failures.append(f"{path.relative_to(ROOT)}: link {target!r} resolves to no file")
    return failures


def check_index() -> list[str]:
    if not INDEX.exists():
        return ["docs/RESULTS.md is missing (run scripts/check-docs.py --write)"]
    if INDEX.read_text(encoding="utf-8") != render_index():
        return ["docs/RESULTS.md is out of date with docs/results/ (run scripts/check-docs.py --write)"]
    return []


def check_family_claim() -> list[str]:
    text = (ROOT / "README.md").read_text(encoding="utf-8")
    found = re.findall(r"\b(\w+) case families\b", text)
    if not found:
        return []
    try:
        sys.path.insert(0, str(ROOT / "src"))
        from ratchet.cases import all_cases
    except ImportError as exc:
        return [f"cannot import the case suite to check the README's family count: {exc}"]
    actual = len({c.family for c in all_cases()})
    failures = []
    for word in found:
        said = NUMBER_WORDS.get(word.lower(), int(word) if word.isdigit() else None)
        if said != actual:
            failures.append(f"README says {word!r} case families; the suite has {actual}")
    return failures


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="regenerate docs/RESULTS.md first")
    args = ap.parse_args()
    if args.write:
        INDEX.write_text(render_index(), encoding="utf-8")
        print(f"wrote {INDEX.relative_to(ROOT)}")
    failures = check_links() + check_index() + check_family_claim()
    for f in failures:
        print("FAIL", f)
    print(f"check-docs: {len(failures)} failure(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
